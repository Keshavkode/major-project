const localeCodes = { en: 'en-US', hi: 'hi-IN', bn: 'bn-IN', ta: 'ta-IN', te: 'te-IN' };
const languageNames = { en: 'English', hi: 'हिन्दी', bn: 'বাংলা', ta: 'தமிழ்', te: 'తెలుగు' };
const languageStorageKey = 'agrisense-language';
let currentLanguage = localStorage.getItem(languageStorageKey);

if (!Object.hasOwn(translations, currentLanguage)) currentLanguage = 'en';

function translate(key, values = {}) {
  const template = translations[currentLanguage][key] ?? translations.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name) => String(values[name] ?? ''));
}

function applyLanguage() {
  document.documentElement.lang = currentLanguage === 'en' ? 'en' : `${currentLanguage}-IN`;

  for (const element of document.querySelectorAll('[data-i18n]')) {
    element.textContent = translate(element.dataset.i18n);
  }
  for (const element of document.querySelectorAll('[data-i18n-aria-label]')) {
    element.setAttribute('aria-label', translate(element.dataset.i18nAriaLabel));
  }
  for (const element of document.querySelectorAll('[data-i18n-placeholder]')) {
    element.setAttribute('placeholder', translate(element.dataset.i18nPlaceholder));
  }
  for (const element of document.querySelectorAll('[data-i18n-title]')) {
    element.setAttribute('title', translate(element.dataset.i18nTitle));
  }
  for (const element of document.querySelectorAll('[data-i18n-content]')) {
    element.setAttribute('content', translate(element.dataset.i18nContent));
  }
  for (const element of document.querySelectorAll('[data-i18n-option]')) {
    element.textContent = translate(element.dataset.i18nOption);
  }
  const title = document.querySelector('[data-i18n-document-title]');
  if (title) document.title = `agriSense | ${translate(title.dataset.i18nDocumentTitle)}`;

  const selector = document.querySelector('#language-select');
  if (selector) selector.value = currentLanguage;
}

function setLanguage(language) {
  if (!Object.hasOwn(translations, language)) return;
  currentLanguage = language;
  localStorage.setItem(languageStorageKey, language);
  applyLanguage();
  document.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
}

function formatNumber(value) {
  return new Intl.NumberFormat(localeCodes[currentLanguage], { maximumFractionDigits: 1 }).format(value);
}

function translateServerError(message, fallbackKey) {
  const serverErrors = {
    'Enter a valid email address.': 'invalidEmail',
    'Password must be at least 8 characters and no more than 72 bytes.': 'invalidPassword',
    'An account with that email already exists.': 'duplicateEmail',
    'Email or password is incorrect.': 'invalidCredentials',
    'Too many account requests. Please try again in a few minutes.': 'rateLimited',
    'Check the crop, field size, soil test, pH, and rainfall values.': 'invalidPlan',
    'Saved plan not found.': 'planMissing',
    'Could not load saved plans.': 'databasePlanError',
  };
  return translate(serverErrors[message] ?? fallbackKey);
}

document.addEventListener('DOMContentLoaded', () => {
  const selector = document.querySelector('#language-select');
  if (selector) selector.addEventListener('change', () => setLanguage(selector.value));
});

applyLanguage();

window.AgriSenseLanguage = {
  formatNumber,
  get currentLanguage() { return currentLanguage; },
  languageNames,
  setLanguage,
  translate,
  translateServerError,
};
